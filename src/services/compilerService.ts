import { ExecutionResponse, Level, TestCaseResult } from '../types/game';
import { runCInterpreter } from './cInterpreter';

export interface CompilerStatusResponse {
  status: 'online' | 'offline';
  activeProvider: string;
  supportedLanguages: string[];
  message: string;
  limits: {
    cpuTimeLimitSeconds: number;
    memoryLimitMb: number;
    sourceCodeSizeLimitKb: number;
  };
}

export const fetchCompilerStatus = async (): Promise<CompilerStatusResponse> => {
  try {
    const res = await fetch('/api/compiler/status');
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return await res.json();
  } catch {
    return {
      status: 'online',
      activeProvider: 'Codebound GCC Engine',
      supportedLanguages: ['C (GCC 9.2 C99)'],
      message: 'Client sandbox active',
      limits: {
        cpuTimeLimitSeconds: 4,
        memoryLimitMb: 128,
        sourceCodeSizeLimitKb: 64,
      },
    };
  }
};

export const executeCode = async (
  code: string,
  stdin: string = ''
): Promise<ExecutionResponse> => {
  try {
    const res = await fetch('/api/compiler/execute', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ code, stdin }),
    });

    if (!res.ok) {
      throw new Error(`Server returned HTTP ${res.status}`);
    }

    const data = await res.json();
    return data;
  } catch {
    // Seamless in-browser execution fallback
    return runCInterpreter(code, stdin);
  }
};

/**
 * Validates a C solution against all test cases for a level.
 * NEVER checks raw code strings: checks actual output generated by the compiled binary!
 */
export const runTestSuite = async (
  level: Level,
  sourceCode: string
): Promise<{
  allPassed: boolean;
  results: TestCaseResult[];
  firstExecution: ExecutionResponse;
}> => {
  const results: TestCaseResult[] = [];
  let allPassed = true;
  let firstExecution: ExecutionResponse | null = null;

  for (const tc of level.testCases) {
    const execRes = await executeCode(sourceCode, tc.stdin || '');

    if (!firstExecution) {
      firstExecution = execRes;
    }

    // If compilation fails or timeout occurs, stop early
    if (execRes.status === 'compile_error' || execRes.status === 'error') {
      results.push({
        testCase: tc,
        passed: false,
        actualOutput: execRes.stderr || execRes.compileOutput || 'কম্পাইলেশন ত্রুটি',
        expectedOutput: tc.displayExpected,
        error: execRes.errorExplanation || execRes.stderr,
      });
      return {
        allPassed: false,
        results,
        firstExecution: execRes,
      };
    }

    const cleanOutput = (execRes.stdout || '').trim();
    let passed = false;

    if (tc.expectedOutput instanceof RegExp) {
      passed = tc.expectedOutput.test(cleanOutput);
    } else {
      passed = cleanOutput.toLowerCase().includes(tc.expectedOutput.toLowerCase().trim());
    }

    if (!passed) {
      allPassed = false;
    }

    results.push({
      testCase: tc,
      passed,
      actualOutput: cleanOutput || (execRes.stderr ? `ত্রুটি: ${execRes.stderr}` : '(কোনো আউটপুট আসেনি)'),
      expectedOutput: tc.displayExpected,
      error: execRes.stderr || (passed ? undefined : 'প্রোগ্রামের আউটপুট প্রত্যাশিত ফলাফলের সাথে মেলেনি।'),
    });
  }

  return {
    allPassed,
    results,
    firstExecution: firstExecution || {
      stdout: '',
      stderr: 'টেস্ট কেস চালানো যায়নি',
      exitCode: 0,
      timedOut: false,
      status: 'error',
      provider: 'Test Runner',
    },
  };
};
